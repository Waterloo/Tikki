#!/usr/bin/env bash
# Renumber a branch's migration during a merge, when its NNNN_name.sql collides with one on the target.
#
# Usage notes
#   Run in the target worktree while `git merge <branch>` is in progress (conflicts are fine), with the
#   merged server/db/schema.ts already resolved:
#
#     scripts/renumber-migration.sh <branch> <old-file-name>
#     scripts/renumber-migration.sh issue-15 0018_issue_15_application_webhook.sql
#
#   Steps:
#     1. Save the branch's SQL (hand edits are the point of keeping it).
#     2. Reset migrations/meta to the target's (HEAD) state; drop meta files only the branch has.
#     3. Remove the branch's SQL from the index and disk.
#     4. `drizzle-kit generate --name <name>` writes the next number, snapshot and journal entry.
#     5. Copy the saved SQL over the generated file, `git add migrations`, run `pnpm lint:migrations`.
#     6. Print a diff, saved vs generated. Read it: it shows what drizzle-kit would have written, so you can
#        see if the schema change and the hand edits still agree after the merge.
#   Exit code is the lint exit code. Refuses to run outside a merge or on a dirty guess (missing file, no schema change).
set -euo pipefail

die() { echo "renumber-migration: $*" >&2; exit 1; }

[ $# -eq 2 ] || die "usage: $0 <branch> <old-file-name>"
branch=$1
old=$(basename "$2"); old=${old%.sql}.sql
cd "$(git rev-parse --show-toplevel)"

git rev-parse -q --verify MERGE_HEAD >/dev/null || die "no merge in progress"
git cat-file -e "$branch:migrations/$old" 2>/dev/null || die "$branch has no migrations/$old"

name=${old%.sql}; name=${name#[0-9][0-9][0-9][0-9]_}
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
git show "$branch:migrations/$old" > "$tmp/saved.sql"

# Meta: the target's journal and snapshots win; drizzle-kit adds the new entry.
for f in $(git diff --name-only --diff-filter=A HEAD "$branch" -- migrations/meta); do
  git rm -q -f --ignore-unmatch -- "$f"; rm -f -- "$f"
done
git checkout HEAD -- migrations/meta

git rm -q -f --ignore-unmatch -- "migrations/$old"; rm -f -- "migrations/$old"

ls migrations/*.sql > "$tmp/before"
pnpm exec drizzle-kit generate --name "$name"
ls migrations/*.sql > "$tmp/after"
new=$(comm -13 "$tmp/before" "$tmp/after")
[ -n "$new" ] && [ "$(echo "$new" | wc -l)" -eq 1 ] || die "drizzle-kit did not write exactly one new file (is schema.ts merged?)"

cp "$new" "$tmp/generated.sql"
cp "$tmp/saved.sql" "$new"
git add migrations
echo "Wrote $new from $branch:migrations/$old"

status=0
pnpm lint:migrations || status=$?

echo
echo "--- diff: generated by drizzle-kit (-) vs saved branch SQL (+) ---"
diff -u "$tmp/generated.sql" "$tmp/saved.sql" || true
exit $status
